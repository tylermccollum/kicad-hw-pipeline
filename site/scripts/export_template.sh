#!/usr/bin/env bash
# Export the hardware tooling as a KiCad project template.
#
#   export_template.sh <dest_dir>
#
# The template is a blank KiCad 10 project named `hwproject` (KiCad renames
# every file containing that name to the new project's name) plus the KiBot
# config, drawing templates, site/ and CI workflow from this repository. No
# design files from this project are included. Point KiCad's template path at
# the parent of <dest_dir>, or copy <dest_dir> into it.
set -euo pipefail

DEST=${1:?usage: export_template.sh <dest_dir>}
SITE=$(cd "$(dirname "$0")/.." && pwd)
REPO=$(dirname "$SITE")
BASE=hwproject
KIBOT_IMAGE=${KIBOT_IMAGE:-ghcr.io/inti-cmnb/kicad10_auto_full@sha256:7b720dc99b2775e4f4133f06887cf9a53c85a8403438d6684ecf0916d124f52a}
pros=("$REPO"/*.kicad_pro)
PROJECT=${PROJECT:-$(basename "${pros[0]}" .kicad_pro)}

# Build in a staging folder; DEST is only replaced once everything succeeded.
# DEST/.git is kept, so the template can be its own repository. Refuse to
# clear a non-empty folder that isn't a previous export.
FINAL=$DEST
if [ -d "$FINAL" ] && [ -n "$(ls -A "$FINAL")" ] \
   && [ ! -f "$FINAL/$BASE.kicad_pro" ] && [ ! -f "$FINAL/meta/info.html" ]; then
  echo "ERROR: $FINAL exists and isn't a previous template export; refusing to overwrite" >&2
  exit 1
fi
DEST=$(mktemp -d "${TMPDIR:-/tmp}/hw-pipeline-export.XXXXXX")
trap 'rm -rf "$DEST"' EXIT
mkdir -p "$DEST/meta" "$DEST/site/content"

# ── Tooling, copied as-is ─────────────────────────────────────────────────────
cd "$REPO"
cp .gitignore "$DEST/"
cp -r kibot_templates "$DEST/"
cp "$PROJECT.kibot.yaml" "$DEST/$BASE.kibot.yaml"
cd "$SITE"
cp -r Makefile go.mod go.sum ci layouts scripts "$DEST/site/"
mkdir -p "$DEST/site/static" && cp -r static/vendor "$DEST/site/static/"
cp content/board.md content/release.md "$DEST/site/content/"

# ── Project-specific files, genericised ──────────────────────────────────────
sed -E \
  -e 's|^title: .*|title: "__PROJECT_TITLE__"|' \
  -e 's|^(  projectName: ).*|\1"__PROJECT_TITLE__"|' \
  -e 's|^(  description: ).*|\1"KiCad hardware project"|' \
  -e 's|^(  repoURL: ).*|\1"__REPO_URL__"|' \
  -e 's|^(  license: ).*|\1""|' \
  -e 's|^(      url: )https://github.com/.*|\1__REPO_URL__|' \
  hugo.yaml > "$DEST/site/hugo.yaml"

cat > "$DEST/site/content/_index.md" <<'EOF'
---
title: Overview
weight: 10
---

<div class="hero-layout">
{{< hero-render >}}
<div>

Describe the board here: what it does, key specs, and status. This page is
`site/content/_index.md`; the render beside it is generated by KiBot.

</div>
</div>
EOF

# ── Blank KiCad 10 project: placeholder 50 x 50 mm outline + 4 M3 holes ─────
cat > "$DEST/.mkblank.py" <<'EOF'
import sys, uuid, pcbnew
d, name = sys.argv[1], sys.argv[2]
mm = pcbnew.FromMM
board = pcbnew.NewBoard(f"{d}/{name}.kicad_pcb")      # also writes .kicad_pro
outline = pcbnew.PCB_SHAPE(board, pcbnew.SHAPE_T_RECT)
outline.SetStart(pcbnew.VECTOR2I(mm(100), mm(70)))
outline.SetEnd(pcbnew.VECTOR2I(mm(150), mm(120)))
outline.SetLayer(pcbnew.Edge_Cuts)
outline.SetWidth(mm(0.05))
board.Add(outline)
# Four M3 mounting holes: realistic placeholder, and the drill table needs holes.
for i, (x, y) in enumerate([(104, 74), (146, 74), (104, 116), (146, 116)], 1):
    fp = pcbnew.FootprintLoad("/usr/share/kicad/footprints/MountingHole.pretty", "MountingHole_3.2mm_M3")
    fp.SetReference(f"H{i}")
    fp.SetPosition(pcbnew.VECTOR2I(mm(x), mm(y)))
    fp.SetBoardOnly(True)            # no schematic symbol needed
    fp.SetExcludedFromBOM(True)
    fp.SetExcludedFromPosFiles(True)
    board.Add(fp)
pcbnew.SaveBoard(f"{d}/{name}.kicad_pcb", board)
open(f"{d}/{name}.kicad_sch", "w").write(
    '(kicad_sch\n\t(version 20260306)\n\t(generator "eeschema")\n\t(generator_version "10.0")\n'
    f'\t(uuid "{uuid.uuid4()}")\n\t(paper "A4")\n\t(lib_symbols)\n'
    '\t(sheet_instances\n\t\t(path "/"\n\t\t\t(page "1")\n\t\t)\n\t)\n\t(embedded_fonts no)\n)\n')
EOF
docker run --rm -u "$(id -u):$(id -g)" -e HOME=/tmp -v "$DEST:/w" -w /w "$KIBOT_IMAGE" \
  python3 .mkblank.py /w "$BASE" 2>&1 | grep -v 'assert' || true
rm -f "$DEST/.mkblank.py" "$DEST/$BASE.kicad_prl"
# B-size sheet (PAGE_INFO isn't usable from Python): fits the 2:1 drawing layout.
sed -i 's/(paper "A4")/(paper "B")/' "$DEST/$BASE.kicad_pcb"
# Deterministic UUIDs, so re-exporting an unchanged template gives identical
# files (keeps the template repo's history clean).
python3 - "$DEST/$BASE.kicad_pcb" "$DEST/$BASE.kicad_sch" <<'PY'
import re, sys, uuid
for path in sys.argv[1:]:
    text, n = open(path).read(), iter(range(10**6))
    name = path.rsplit("/", 1)[-1]
    # KiCad saves footprints in (random) UUID order: sort them by reference.
    fps = re.findall(r'\n\t\(footprint .*?\n\t\)', text, re.S)
    if fps:
        first = text.index(fps[0])
        rest = text[first:]
        for fp in fps:
            rest = rest.replace(fp, "", 1)
        ref = lambda fp: re.search(r'\(property "Reference" "([^"]*)"', fp).group(1)
        text = text[:first] + "".join(sorted(fps, key=ref)) + rest
    def stable(m):
        return '(uuid "%s")' % uuid.uuid5(uuid.NAMESPACE_URL, "hw-pipeline/%s/%d" % (name, next(n)))
    text = re.sub(r'\(uuid "[0-9a-f-]+"\)', stable, text)
    open(path, "w").write(text)
PY
[ -f "$DEST/$BASE.kicad_pcb" ] && [ -f "$DEST/$BASE.kicad_pro" ] || { echo "ERROR: blank project not created" >&2; exit 1; }

# ── Docs: KiCad's template chooser page and the new project's README ─────────
cat > "$DEST/meta/info.html" <<'EOF'
<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>Hardware pipeline (KiBot + Hugo)</title></head>
<body>
<h2>Hardware pipeline (KiBot + Hugo)</h2>
<p>Blank KiCad 10 project with a containerised manufacturing and documentation
pipeline: KiBot outputs (schematic PDF, BOMs, iBOM, 3D renders, diffs, JLCPCB
package), fabrication and assembly drawings with templated notes, and a
versioned Hugo site that can be hosted locally or on GitHub Pages.</p>
<p>After creating the project, close it in KiCad and run
<code>make -C site init</code> in the project folder. See README.md.</p>
<p>Needs docker, git, rsync, jq, zip and python3.</p>
</body></html>
EOF

cat > "$DEST/README.md" <<'EOF'
<!-- hw-pipeline template README: `make -C site init` replaces this file with
     site/README.project.md in projects created from the template. -->
# KiCad hardware pipeline template

A KiCad 10 project template with a containerised manufacturing and
documentation pipeline:

- **KiBot outputs**: schematic PDF, HTML BOM, interactive BOM, raytraced 3D
  renders, schematic/PCB diffs against the previous tag, and a JLCPCB
  package (gerbers, drill, BOM, CPL).
- **Fabrication and assembly drawings** (PDF) with templated notes and data
  tables, laid out and scaled automatically for the board and sheet size.
- **A versioned documentation site** (Hugo) with an embedded schematic/PCB
  viewer, hosted locally or on GitHub Pages.
- **CI**: pull requests build the site, `main` publishes it, `v*` tags make a
  strict release (ERC/DRC must pass) with packages attached.

Everything runs in Docker. The host needs `docker`, `git`, `make`, `rsync`,
`jq`, `zip` and `python3`, and a Linux-like shell (see *Platforms* below).

## Install

Clone this repository into KiCad's user template folder (KiCad skips the
`.git` folder when creating projects):

| OS | KiCad 10 user template folder |
|---|---|
| Linux | `~/.local/share/kicad/10.0/template/` |
| macOS | `~/Documents/KiCad/10.0/template/` |
| Windows | `%USERPROFILE%\Documents\KiCad\10.0\template\` |

(KiCad → Preferences → Configure Paths → `KICAD_USER_TEMPLATE_DIR` shows the
exact location.)

## Create a project

1. In KiCad: **File → New Project from Template → User Templates →
   Hardware pipeline**, choose a folder and name. Every file named
   `hwproject.*` is renamed to your project name.
2. **Close the project in KiCad**, then in the new project folder:

   ```sh
   TITLE="My Board" make -C site init
   ```

   This initialises git (if needed), installs `.github/workflows/ci.yml`
   (KiCad templates can't carry hidden folders, so its source lives in
   `site/ci/`), fills the site title and GitHub URL into `site/hugo.yaml`
   (re-run after adding an `origin` remote), adds the empty drawing layers
   (DrillMap, FabNotes, Dimensions, AsmNotes, AsmCover) for your own
   annotations, and replaces this README with a project README.
3. Replace the placeholder 50 x 50 mm outline and mounting holes with your
   design, then build:

   ```sh
   make -C site kibot build host     # http://127.0.0.1:8000/
   ```

## Using the pipeline

See `README.md` in the created project (from `site/README.project.md`).

## Platforms

- **Linux**: native.
- **Windows**: use WSL2 with Docker Desktop's WSL integration, and keep the
  project inside the WSL filesystem (KiCad for Windows can open it via
  `\\wsl$\...`). Native PowerShell/cmd is not supported.
- **macOS**: needs GNU tools from Homebrew
  (`brew install bash coreutils gnu-sed findutils rsync make`) with their
  `gnubin` directories first in `PATH`. On Apple Silicon the KiCad container
  runs under x86-64 emulation, which is slower.

## Maintaining this template

This template is exported from a working project with
`make -C site export-template DEST=<this folder>`; the export keeps `.git`
and replaces everything else, so make changes in the source project and
re-export, then commit here.
EOF

cat > "$DEST/site/README.project.md" <<'EOF'
# __PROJECT_TITLE__

Describe the board here.

## Hardware pipeline

Everything runs in Docker; the host needs `docker`, `git`, `make`, `rsync`,
`jq`, `zip` and `python3`.

```sh
make -C site kibot build host        # outputs -> generated/, site -> http://127.0.0.1:8000/
make -C site serve                   # live-reload site at http://localhost:1313/
make -C site release TAG=v1.0.0      # strict ERC/DRC, packages in build/releases/
make -C site help                    # all targets
```

- `<project>.kibot.yaml` is the single KiBot config: schematic PDF, HTML BOM,
  iBOM, raytraced renders, schematic/PCB diffs against the previous tag,
  JLCPCB gerbers/drill/BOM/CPL, and the fabrication and assembly drawings.
- Drawing tables and note blocks are CSV templates in `kibot_templates/`;
  `${VAR}` is filled at build time from environment variables, project text
  variables or board statistics (e.g. `${thickness_mm}`, `${pcb_finish_cap}`,
  `${REVISION}`).
- The drawing layout is automatic and never written to your board: each build
  picks the largest standard scale (5:1 down to 1:10) at which the board, its
  dimensions, notes and tables fit the sheet, sizes table text to print ~2 mm
  wide, and places the tables, cover image and outline dimensions, all in a
  throwaway copy. Resize the board or change the sheet (Page Settings) and the
  next build adapts. Anything you draw yourself on the drawing layers is kept.
- To place things by hand, `make -C site pin-layout` (KiCad closed) copies the
  current layout into the board as `kibot_table_*` / `kibot_image_*` groups and
  fixes the scale; move them in the PCB editor. Delete a group to make it
  automatic again, or `make -C site unpin-layout` to remove them all.
- `site/` is a Hugo site using the
  [hugo-kicad-site](https://github.com/laenzlinger/hugo-kicad-site) theme
  (GPL-3.0) by laenzlinger, with a vendored
  [KiCanvas](https://kicanvas.org) viewer (MIT; `make -C site vendor-kicanvas`
  to refresh). Edit the pages in `site/content/`.

### Publishing (GitHub Pages)

`.github/workflows/ci.yml` runs the same `make` targets: pull requests build
the site as an artifact, pushes to `main` publish `/latest/`, and `v*` tags run
a strict release, attach the packages to a GitHub Release and publish
`/<tag>/`. To enable publishing (public repo): Settings → Pages → deploy from
branch `gh-pages`, then add the Actions variable `PAGES_DEPLOY` = `true`.
EOF

mkdir -p "$FINAL"
FINAL=$(cd "$FINAL" && pwd)
find "$FINAL" -mindepth 1 -maxdepth 1 ! -name .git -exec rm -rf {} +
cp -a "$DEST/." "$FINAL/"
echo "Template written to $FINAL"
find "$FINAL" -maxdepth 2 -not -path '*/static/*' -not -path '*/.git/*' -not -name .git | sort | sed "s|$FINAL|.|"
